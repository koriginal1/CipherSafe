-- Run this in Supabase Dashboard > SQL Editor > New query.
-- Stores operation metadata only; it does not store messages or encryption keys.

create table if not exists public.operations (
    id bigint generated by default as identity primary key,
    timestamp timestamptz not null default now(),
    operation_type text not null,
    algorithm text not null,
    message_length integer not null check (message_length >= 0),
    status text not null check (status in ('Success', 'Failed'))
);

-- The Flask server uses SUPABASE_SERVICE_ROLE_KEY, which bypasses RLS.
-- Enable RLS to prevent browser/anon clients from accessing this table directly.
alter table public.operations enable row level security;

-- Do not add public/anon policies for this table. Access it only from Flask.
